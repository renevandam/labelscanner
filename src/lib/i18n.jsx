const KEY = 'labelscanner.lang'
const LangContext = createContext(null)

function initialLang() {
  try {
    const saved = localStorage.getItem(KEY)
    if (saved === 'nl' || saved === 'en') return saved
  } catch { /* geen opslag */ }
  return (navigator.language || 'nl').toLowerCase().startsWith('nl') ? 'nl' : 'en'
}

// Vertaal los van React (bv. in de Excel-export), met dezelfde regels.
export function translate(lang, key, vars) {
  let s = DICT[lang]?.[key] ?? DICT.nl[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  // Meervoud: "label(s)" → "label" bij 1, anders "labels"; "foto('s)" → "foto"/"foto's"
  const n = vars?.n
  if (n !== undefined) s = s.replace(/\((s|'s)\)/g, (_, p) => (Number(n) === 1 ? '' : p))
  return s
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(initialLang)
  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem(KEY, l) } catch { /* geen opslag */ }
  }, [])
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const value = useMemo(() => ({
    lang,
    setLang,
    t: (key, vars) => translate(lang, key, vars),
    locale: lang === 'nl' ? 'nl-NL' : 'en-GB',
  }), [lang, setLang])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}

export function LangSwitch() {
  const { lang, setLang, t } = useLang()
  return (
    <div className="langswitch" role="group" aria-label={t('lang.label')}>
      {['nl', 'en'].map((l) => (
        <button key={l} type="button" className={lang === l ? 'on' : ''} aria-pressed={lang === l} onClick={() => setLang(l)}>
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  )
}
